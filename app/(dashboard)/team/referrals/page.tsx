"use client";

import * as React from "react";
import Link from "next/link";
import { ArrowRight, CheckCircle2, HelpCircle, QrCode, Users } from "lucide-react";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { DemoDataBadge } from "@/components/shared/demo-data-badge";
import { PageHeader } from "@/components/shared/page-header";
import { CardSkeleton, EmptyState, ErrorState } from "@/components/shared/states";
import { QrCodeGraphic, ReferralLinkCard } from "@/components/team/team-components";
import { useApiQuery } from "@/hooks/use-api";
import { RANK_META } from "@/lib/constants";
import { getCommissionRules, getReferralActivity, getTeamSummary, validateInviteCode } from "@/lib/services/team";
import { getProfile } from "@/lib/services/profile";
import { formatKES, relativeTime } from "@/lib/utils";
import { toast } from "sonner";
import type { ReferralActivity } from "@/lib/types";

const EVENT_LABEL: Record<ReferralActivity["event"], string> = {
  signup: "Joined",
  verified: "Verified",
  invested: "Invested",
  reward: "Reward earned",
};

export default function ReferralsPage() {
  const profile = useApiQuery(["profile", "me"], getProfile);
  const summary = useApiQuery(["team", "summary"], getTeamSummary);
  const rules = useApiQuery(["team", "commission-rules"], getCommissionRules);
  const activity = useApiQuery(["team", "activity"], getReferralActivity);

  const [inviteCode, setInviteCode] = React.useState("");
  const [checking, setChecking] = React.useState(false);
  const [sponsor, setSponsor] = React.useState<string | null>(null);
  const [inviteError, setInviteError] = React.useState<string | null>(null);

  const code = profile.data?.referralCode ?? "";
  const url = `/register?inviteCode=${encodeURIComponent(code)}`;

  const checkCode = async () => {
    const value = inviteCode.trim();
    if (!value) {
      setInviteError("Enter an invite code to check.");
      setSponsor(null);
      return;
    }
    setChecking(true);
    setInviteError(null);
    setSponsor(null);
    const res = await validateInviteCode(value);
    setChecking(false);
    if (!res.ok) {
      setInviteError(res.message);
      return;
    }
    setSponsor(res.data.sponsorName);
  };

  return (
    <div className="space-y-6 animate-fade-up">
      <PageHeader
        title="Invite centre"
        description="Share your invite link and follow three-level team rewards in your account."
        breadcrumbs={[{ label: "Team", href: "/team" }, { label: "Invite centre" }]}
        actions={<DemoDataBadge />}
      />

      <div className="grid gap-6 lg:grid-cols-2">
        <div className="space-y-6">
          {profile.isPending && <CardSkeleton lines={4} />}
          {profile.isError && (
            <ErrorState title="Could not load your invite code" description={profile.error?.message} onRetry={() => void profile.refetch()} />
          )}
          {profile.data && <ReferralLinkCard code={profile.data.referralCode} url={url} />}

          <Card>
            <CardHeader>
              <CardTitle className="flex items-center justify-between text-base">
                <span>Scan to join</span>
                <QrCode className="text-muted-foreground size-4" />
              </CardTitle>
            </CardHeader>
            <CardContent className="flex flex-col items-center gap-3 text-center">
              <QrCodeGraphic value={url} size={184} />
              <p className="text-sm font-bold">Point a camera at the code to open the invite</p>
              <p className="text-xs text-muted-foreground">
                This decorative QR code is not scannable. Copy and share the invite link below.
              </p>
            </CardContent>
          </Card>
        </div>

        <div className="space-y-6">
          <Card>
            <CardHeader>
              <CardTitle className="text-base">How referral rewards work</CardTitle>
            </CardHeader>
            <CardContent className="space-y-3">
              <p className="text-sm text-muted-foreground leading-relaxed">
                Earn a commission on the volume generated by members you invite — and by the people they invite, three levels deep.
                Rates improve as your rank rises.
              </p>
              {rules.isPending && <CardSkeleton lines={3} />}
              {rules.isError && (
                <ErrorState title="Could not load commission rules" description={rules.error?.message} onRetry={() => void rules.refetch()} />
              )}
              {rules.data && (
                <div className="grid gap-3 sm:grid-cols-3">
                  {rules.data
                    .slice()
                    .sort((a, b) => a.level - b.level)
                    .map((rule) => (
                      <div key={rule.id} className="rounded-lg border border-border bg-card p-4 shadow-xs">
                        <div className="flex items-center justify-between">
                          <Badge variant="secondary">Level {rule.level}</Badge>
                          <span className="numeric text-lg font-extrabold text-primary">{rule.percent}%</span>
                        </div>
                        <p className="mt-2 text-sm font-bold">{rule.name}</p>
                        <p className="mt-0.5 text-xs text-muted-foreground">
                          Min rank {RANK_META[rule.minRank].label}
                          {!rule.active && " · paused"}
                        </p>
                      </div>
                    ))}
                </div>
              )}
            </CardContent>
          </Card>

          <Card>
            <CardHeader>
              <CardTitle className="flex items-center justify-between text-base">
                <span>Check an invite code</span>
                <HelpCircle className="text-muted-foreground size-4" />
              </CardTitle>
            </CardHeader>
            <CardContent className="space-y-3">
              <div className="space-y-2">
                <Label htmlFor="invite-code">Invite code</Label>
                <div className="flex gap-2">
                  <Input
                    id="invite-code"
                    value={inviteCode}
                    onChange={(e) => setInviteCode(e.target.value.toUpperCase())}
                    placeholder="e.g. ALEX2481"
                    className="numeric uppercase"
                    aria-invalid={!!inviteError}
                  />
                  <Button onClick={() => void checkCode()} disabled={checking}>
                    {checking ? "Checking…" : "Check"}
                  </Button>
                </div>
                {inviteError && <p role="alert" className="text-xs font-semibold text-danger">{inviteError}</p>}
              </div>
              {sponsor && (
                <Alert variant="success">
                  <CheckCircle2 />
                  <AlertTitle>Code recognised</AlertTitle>
                  <AlertDescription>
                    Sponsored by <span className="font-bold">{sponsor}</span>. Enter this code when creating an account to join their team.
                  </AlertDescription>
                </Alert>
              )}
              <p className="text-xs text-muted-foreground">
                Your invite code is <span className="numeric font-bold text-foreground">{code || "—"}</span>.
              </p>
            </CardContent>
          </Card>

          <Card>
            <CardHeader>
              <CardTitle className="flex items-center justify-between text-base">
                <span>Invite stats</span>
                <Users className="text-muted-foreground size-4" />
              </CardTitle>
            </CardHeader>
            <CardContent className="grid grid-cols-3 gap-3">
              <div className="rounded-lg border border-border bg-muted/50 p-3 text-center">
                <p className="numeric text-xl font-extrabold">{summary.data?.totalMembers ?? "—"}</p>
                <p className="mt-0.5 text-[11px] text-muted-foreground">Total invited</p>
              </div>
              <div className="rounded-lg border border-border bg-muted/50 p-3 text-center">
                <p className="numeric text-xl font-extrabold">{summary.data?.activeMembers ?? "—"}</p>
                <p className="mt-0.5 text-[11px] text-muted-foreground">Active joiners</p>
              </div>
              <div className="rounded-lg border border-border bg-muted/50 p-3 text-center">
                <p className="numeric text-xl font-extrabold">
                  {summary.data ? formatKES(summary.data.totalRewards, { decimals: 0 }) : "—"}
                </p>
                <p className="mt-0.5 text-[11px] text-muted-foreground">Earned from invites</p>
              </div>
            </CardContent>
          </Card>
        </div>
      </div>

      <Card>
        <CardHeader>
          <div className="flex flex-wrap items-center justify-between gap-2">
            <CardTitle className="text-base">Referral activity</CardTitle>
            <Button asChild variant="link" size="sm">
              <Link href="/team">
                Team overview <ArrowRight />
              </Link>
            </Button>
          </div>
        </CardHeader>
        <CardContent>
          {activity.isPending && (
            <div className="space-y-3">
              <CardSkeleton lines={1} />
              <CardSkeleton lines={1} />
            </div>
          )}
          {activity.isError && (
            <ErrorState title="Could not load referral activity" description={activity.error?.message} onRetry={() => void activity.refetch()} />
          )}
          {activity.data && activity.data.length === 0 && (
            <EmptyState
              title="No referral activity yet"
              description="Once people join with your code, their signups and rewards will show up here."
              action={
                <Button asChild>
                  <Link href="/team">Back to team</Link>
                </Button>
              }
            />
          )}
          {activity.data && activity.data.length > 0 && (
            <ul className="divide-border space-y-3 divide-y">
              {activity.data.map((a) => (
                <li key={a.id} className="flex items-start gap-3 py-3 first:pt-0 last:pb-0">
                  <Badge variant="outline" className="shrink-0">
                    L{a.level}
                  </Badge>
                  <div className="min-w-0 flex-1">
                    <div className="flex flex-wrap items-center gap-2">
                      <p className="truncate text-sm font-bold">{a.memberName}</p>
                      <Badge variant={a.event === "reward" ? "success" : a.event === "signup" ? "info" : "secondary"}>
                        {EVENT_LABEL[a.event]}
                      </Badge>
                    </div>
                    <p className="mt-0.5 text-xs text-muted-foreground">{a.detail}</p>
                  </div>
                  <div className="shrink-0 text-right">
                    {a.amount !== undefined && (
                      <p className="numeric text-sm font-extrabold">{formatKES(a.amount, { decimals: 0 })}</p>
                    )}
                    <p className="text-[11px] text-muted-foreground">{relativeTime(a.at)}</p>
                  </div>
                </li>
              ))}
            </ul>
          )}
        </CardContent>
      </Card>
    </div>
  );
}
